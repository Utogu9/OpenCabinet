// JSON files are the editable source. This small browser bundle is generated.
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '../src/locales');
const catalogs = {};
for (const file of fs.readdirSync(root).filter(file => /^[a-z]{2,3}-[A-Z]{2}\.json$/.test(file)).sort()) {
  const catalog = JSON.parse(fs.readFileSync(path.join(root, file), 'utf8'));
  if (catalog._meta.locale + '.json' !== file || !catalog._meta.name || !catalog.messages) throw Error(`Invalid locale: ${file}`);
  catalogs[catalog._meta.locale] = catalog;
}
if (!catalogs['es-AR']) throw Error('Missing es-AR fallback catalog');
const output = '// Generated by npm run prepare:locales. Edit the JSON catalogs instead.\n' +
  'globalThis.OpenCabinetLocaleCatalogs = ' + JSON.stringify(catalogs) + ';\n';
const destination = path.join(root, 'catalogs.js');
if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== output) fs.writeFileSync(destination, output);
